# effects_all_failed
# ---------------------------------------------------------------------------


def _is_effect_call(item: Evidence) -> bool:
    """A call that writes a file or sends something.

    ``run_python`` is not one (its code is not read here), nor is a ``bash`` command or an MCP tool the
    ledger classes ``external`` (that class covers reads such as a GET or a fetch).
    """
    if item.tool_name in _WRITE_OR_SEND_TOOLS:
        return item.side_effect != "none"
    if item.tool_name == "bash" or item.tool_name.startswith("mcp__"):
        return item.side_effect in _CHANGE_CLASSES
    return False


def _failed(item: Evidence) -> bool:
    """The call failed, was refused or timed out, or (bash) exited non-zero."""
    return not item.ok or (item.tool_name == "bash" and item.exit_code not in (None, 0))


def effects_all_failed(text: str, evidence: Sequence[Evidence]) -> int:
    """How many calls tried to change something, when all of them failed and the report names no failure; else 0."""
    effects = [item for item in evidence if _is_effect_call(item)]
    if not effects or not all(_failed(item) for item in effects):
        return 0
    if _FAILURE_WORDS.search(_DENIED_FAILURE.sub(" ", text.replace("\u2019", "'"))):
        return 0
    return len(effects)


