def _whole_sentences(text: str) -> str:
    """``text`` when it ends within ``MAX_TEXT_CHARS``; otherwise its first ``MAX_TEXT_CHARS`` without the
    sentence the cut ends inside (a cut path or a cut-off hedge is not read)."""
    if len(text) <= MAX_TEXT_CHARS:
        return text
    cut = text[:MAX_TEXT_CHARS]
    ends = [m.start() for m in _SENTENCE_END.finditer(cut) if m.start() < len(cut)]
    return cut[: ends[-1]] if ends else ""


def _mostly_ascii_letters(text: str) -> bool:
    """Whether at least half of the letters of the report's prose (code and paths left out) are ASCII.

    The word lists of both checks are English: a report written in another alphabet is not checked.
    """
    prose = _BACKTICKED.sub(" ", _FENCE.sub(" ", text))
    letters = [c for word in prose.split() if "/" not in word for c in word if c.isalpha()]
    return bool(letters) and 2 * sum(c.isascii() for c in letters) >= len(letters)


def evaluate(text: str, evidence: Sequence[Evidence], workspace_dir: str, exists: Exists) -> FinishVerdict:
    """Run both checks over the first ``MAX_TEXT_CHARS`` of ``text`` (``named_file_missing`` over its whole
    sentences only).

    ``not_checked`` / ``non_ascii_text`` for a report not mostly written in ASCII letters; otherwise
    ``clean`` when no check finds anything and ``flagged`` when one does, with the skipped checks named. A
    check that raises makes the verdict ``not_checked`` / ``check_error``; the error is logged by its class
    name only.
    """
    failed: list[str] = []
    skipped: list[str] = []
    try:
        if not _mostly_ascii_letters(text[:MAX_TEXT_CHARS]):
            return FinishVerdict("not_checked", why="non_ascii_text")
        missing = named_file_missing(_whole_sentences(text), evidence, workspace_dir, exists)
        if missing is None:
            skipped.append(NAMED_FILE_MISSING)
        elif missing:
            failed.append(NAMED_FILE_MISSING)
        if effects_all_failed(text[:MAX_TEXT_CHARS], evidence):
            failed.append(EFFECTS_ALL_FAILED)
    except Exception as exc:
        logger.warning("F113: a finish check failed (%s)", type(exc).__name__)
        return FinishVerdict("not_checked", why="check_error")
    return FinishVerdict("flagged" if failed else "clean", failed=tuple(failed), skipped=tuple(skipped))


def record_of(verdict: FinishVerdict, mode: str) -> dict[str, Any]:
    """The ``finish_check`` record kept in ``heart.subtasks.metadata``: labels only."""
    return {
        "v": RECORD_VERSION,
        "mode": mode,
        "verdict": verdict.verdict,
        "failed": list(verdict.failed),
        "skipped": list(verdict.skipped),
        "why": verdict.why,
    }


def finish_check_counts(records: Iterable[Any], mode: str) -> dict[str, Any]:
    """Counts of ``finish_check`` records, for a dashboard block over completed tasks.

    ``records`` are the ``metadata->'finish_check'`` values of the completed rows to count (None for a
    row that has none, which is counted nowhere). Keys:

    - ``checked``: rows with verdict ``clean`` or ``flagged``;
    - ``flagged``: rows with verdict ``flagged`` (any check);
    - ``not_checked``: rows with verdict ``not_checked``;
    - ``mode``: the ``mode`` passed in (the setting now);
    - ``by_check``: per check name, ``checked`` (a ``clean`` or ``flagged`` row where that check was not
      skipped) and ``flagged`` (rows where it found a mismatch). A check's share is flagged / checked.
    """
    by_check = {name: {"checked": 0, "flagged": 0} for name in CHECK_NAMES}
    counts: dict[str, Any] = {"checked": 0, "flagged": 0, "not_checked": 0, "mode": mode, "by_check": by_check}
    for record in records:
        verdict = record.get("verdict") if isinstance(record, Mapping) else None
        if verdict == "not_checked":
            counts["not_checked"] += 1
            continue
        if verdict not in ("clean", "flagged"):
            continue
        counts["checked"] += 1
        counts["flagged"] += verdict == "flagged"
        failed = record.get("failed") or []
        skipped = record.get("skipped") or []
        for name, check in by_check.items():
            if name in failed:
                check["checked"] += 1
                check["flagged"] += 1
            elif name not in skipped:
                check["checked"] += 1
    return counts
