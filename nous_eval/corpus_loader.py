# Public entry point
# ---------------------------------------------------------------------------


async def load_corpus_from_jsonl(
    db: Database,
    jsonl_dir: Path,
    agent_id: str,
    fixture_version: str,
    embedding_dim: int = 1536,
) -> CorpusStats:
    """Load all memory-type JSONL dumps from ``jsonl_dir`` into the eval DB.

    Idempotent on ``agent_id``: re-running with existing facts no-ops.
    Per-row failures are logged into ``stats.errors`` instead of aborting.
    Writes ``nous_eval_meta`` rows so the harness startup probe can
    confirm version alignment.
    """
    if not jsonl_dir.exists():
        raise FileNotFoundError(f"Corpus JSONL dir missing: {jsonl_dir}")

    await _ensure_meta_table(db)

    # Idempotency check via SQLAlchemy session (cheap).
    async with db.session() as session:
        existing = await _existing_agent_counts(session, agent_id)
    if existing.get("facts", 0) > 0:
        logger.info(
            "agent_id=%s already has corpus (%s); skipping load",
            agent_id, existing,
        )
        return CorpusStats()

    stats = CorpusStats()

    # Switch to direct asyncpg for the bulk insert path. Each row runs
    # in its own subtransaction so a single FK/type failure doesn't
    # abort the whole load.
    raw_url = db.engine.url.render_as_string(hide_password=False).replace(
        "postgresql+asyncpg://", "postgresql://"
    )
    conn = await asyncpg.connect(raw_url)
    try:
        await conn.set_type_codec(
            "jsonb",
            encoder=json.dumps, decoder=json.loads,
            schema="pg_catalog",
        )
        await conn.set_type_codec(
            "json",
            encoder=json.dumps, decoder=json.loads,
            schema="pg_catalog",
        )

        for memory_type, (filename, table) in _CORPUS_FILES.items():
            file_path = jsonl_dir / filename
            if not file_path.exists():
                logger.warning(
                    "Corpus file missing for %s: %s (skipping)",
                    memory_type, file_path,
                )
                continue
            loaded = await _load_one_type(
                conn, file_path, memory_type, table,
                agent_id, embedding_dim, stats,
            )
            # Map to the singular -> plural attribute on stats
            attr = {
                "fact": "facts", "decision": "decisions",
                "episode": "episodes", "procedure": "procedures",
                "censor": "censors", "graph_edge": "graph_edges",
            }[memory_type]
            setattr(stats, attr, loaded)
    finally:
        await conn.close()

    # Meta write goes back through SQLAlchemy session (matches existing
    # contract for callers that introspect via session).
    async with db.session() as session:
        await _write_meta(session, fixture_version, stats)
        await session.commit()

    logger.info("Corpus load complete: %s", stats.to_dict())
    return stats


