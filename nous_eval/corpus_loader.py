async def _ensure_meta_table(db: Database) -> None:
    """Create ``nous_eval_meta`` if missing. Idempotent.

    Schema is key/value (matches Dockerfile.eval-db.load.sh).
    """
    async with db.session() as session:
        await session.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS nous_eval_meta (
                    key   TEXT PRIMARY KEY,
                    value TEXT NOT NULL
                )
                """
            )
        )
        await session.commit()


async def _existing_agent_counts(session, agent_id: str) -> dict[str, int]:
    """Return current row counts per table for ``agent_id``."""
    counts: dict[str, int] = {}
    for schema_table, key in [
        ("heart.facts", "facts"),
        ("brain.decisions", "decisions"),
        ("heart.episodes", "episodes"),
        ("heart.procedures", "procedures"),
    ]:
        try:
            result = await session.execute(
                text(f"SELECT COUNT(*) FROM {schema_table} WHERE agent_id = :aid"),
                {"aid": agent_id},
            )
            counts[key] = int(result.scalar() or 0)
        except Exception as exc:
            logger.debug("Count failed for %s: %s", schema_table, exc)
            counts[key] = 0
    return counts


def _coerce_value(v: Any) -> Any:
    """Convert ISO datetime strings to ``datetime`` objects.

    Other strings (UUIDs, vector literals, plain text) pass through —
    asyncpg auto-handles uuid string -> uuid column casts; vectors
    are bound separately with explicit ``::vector`` casts in the SQL.
    """
    if isinstance(v, str) and _ISO_DATETIME_RE.match(v):
        try:
            return datetime.fromisoformat(v)
        except ValueError:
            return v
    return v


def _prepare_row(row: dict, agent_id: str, embedding_dim: int) -> tuple[dict, str | None]:
    """Mutate ``row`` into a form asyncpg can bind cleanly.

    Returns ``(prepared_row, error_message_or_None)``. If error_message
    is non-None, the row should be skipped.
    """
    # Drop trigger-generated columns
    for col in _AUTO_GENERATED_COLUMNS:
        row.pop(col, None)

    # NULL out FK columns (cross-row order independence)
    for col in _FK_NULL_COLUMNS:
        if col in row:
            row[col] = None

    # JSONB-string -> Python object
    for col in _JSONB_COLUMNS:
        if col in row and isinstance(row[col], str):
            try:
                row[col] = json.loads(row[col])
            except (json.JSONDecodeError, TypeError):
                pass  # leave as string; asyncpg will probably reject it

    # ISO timestamp -> datetime
    for col in list(row):
        row[col] = _coerce_value(row[col])

    # Validate embedding (dim check). The string form ``[0.1,0.2,...]`` is
    # also acceptable (pgvector accepts that with explicit ::vector cast).
    emb = row.get("embedding")
    if emb is not None:
        if isinstance(emb, list):
            if len(emb) != embedding_dim:
                return row, f"embedding dim {len(emb)} != {embedding_dim}"
            row["embedding"] = _pgvector_literal(emb)
        elif isinstance(emb, str) and not emb.startswith("["):
            return row, f"embedding string not in pgvector literal form"

    # Force agent_id (in case the dump had a different one).
    row["agent_id"] = agent_id

    return row, None


async def _load_one_type(
    conn: asyncpg.Connection,
    file_path: Path,
    memory_type: str,
    table: str,
    agent_id: str,
    embedding_dim: int,
    stats: CorpusStats,
) -> int:
    """Load one JSONL file into ``table`` via per-row asyncpg subtransactions.

    Each insert runs in ``async with conn.transaction()`` so a single
    constraint or type failure rolls back only that row, leaving the
    overall load to continue. Failed rows accumulate in ``stats.errors``.
    """
    rows = []
    with file_path.open("r", encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, start=1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                stats.errors.append(f"{file_path.name}:{lineno} JSON error: {exc}")
                continue
            prepared, err = _prepare_row(row, agent_id, embedding_dim)
            if err is not None:
                stats.skipped_bad_embedding += 1
                stats.errors.append(f"{file_path.name}:{lineno} {err}")
                continue
            rows.append((lineno, prepared))

    if not rows:
        logger.info("Loaded 0 %s rows from %s (file empty)", memory_type, file_path.name)
        return 0

    # Build INSERT once per file using the union of all column names.
    # Rows missing a column will get NULL via .get().
    cols = sorted({k for _, r in rows for k in r.keys()})
    placeholders = []
    for i, c in enumerate(cols, start=1):
        if c == "embedding":
            placeholders.append(f"${i}::vector")
        else:
            placeholders.append(f"${i}")
    col_list = ", ".join(f'"{c}"' for c in cols)
    sql = (
        f"INSERT INTO {table} ({col_list}) "
        f"VALUES ({', '.join(placeholders)}) "
        f"ON CONFLICT DO NOTHING"
    )

    loaded = 0
    for lineno, row in rows:
        vals = [row.get(c) for c in cols]
        try:
            async with conn.transaction():
                await conn.execute(sql, *vals)
                loaded += 1
        except Exception as exc:
            stats.errors.append(
                f"{file_path.name}:{lineno} insert failed: "
                f"{type(exc).__name__}: {str(exc)[:200]}"
            )

    logger.info(
        "Loaded %d/%d %s rows from %s (%d errors)",
        loaded, len(rows), memory_type, file_path.name,
        len(rows) - loaded,
    )
    return loaded


def _pgvector_literal(vec: list[float]) -> str:
    """Convert a Python list to a pgvector string literal."""
    return "[" + ",".join(f"{x:.8f}" for x in vec) + "]"


async def _write_meta(session, fixture_version: str, stats: CorpusStats) -> None:
    """Upsert nous_eval_meta rows for this fixture version.

    Schema is key/value (matches Dockerfile.eval-db.load.sh). Stored keys:
      - fixture_version (the active tag)
      - loaded_at        (ISO 8601 timestamp)
      - corpus_counts    (JSON-encoded CorpusStats payload)
    """
    now = datetime.now(tz=timezone.utc)
    payload = stats.to_dict()
    rows = [
        ("fixture_version", fixture_version),
        ("loaded_at", now.isoformat()),
        ("corpus_counts", json.dumps(payload)),
    ]
    for key, value in rows:
        await session.execute(
            text(
                """
                INSERT INTO nous_eval_meta (key, value)
                VALUES (:k, :v)
                ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value
                """
            ),
            {"k": key, "v": value},
        )
